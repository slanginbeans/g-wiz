from PIL import Image
# 32x32 pixel-art app icon: wizard hat with stars over a checkerboard "transparent" canvas.
P={'.':None,'k':(0,0,0,255),'w':(255,255,255,255),'g':(128,128,128,255),'s':(192,192,192,255),'n':(0,0,128,255),
   'b':(0,0,255,255),'y':(255,255,0,255),'o':(255,176,32,255),'r':(255,0,0,255),'f':(255,0,255,255),'c':(0,255,255,255)}
art = """
................................
................................
..................kkk...........
................kkbbk.....y.....
...............kbbbk.....yyy....
..............kbbbk.......y.....
.............kbbbbk.............
............kbbybbk.............
...........kbbyyybk.............
...........kbbbybbbk.......y....
..........kbbbbbbbbk............
..........kbbbbbbbbbk...........
.........kbbbbbbbybbk...........
.........kbbbbbbyyybbk..........
........kbbybbbbbybbbk..........
........kbyyybbbbbbbbbk.........
.......kbbbybbbbbbbbbbk.........
.......kyyyyyyyyyyyyyyyk........
......kyyyyyyyyyyyyyyyyyk.......
...kkkkkkkkkkkkkkkkkkkkkkkkk....
..knnnnnnnnnnnnnnnnnnnnnnnnnk...
..kkkkkkkkkkkkkkkkkkkkkkkkkkk...
..kwswswswswswswswswswswswsk....
..kswswswswswswswswswswswswk....
..kwswswswswswswswswswswswsk....
..kswswswswswswswswswswswswk....
..kwswswswswswswswswswswswsk....
..kswswswswswswswswswswswswk....
..kkkkkkkkkkkkkkkkkkkkkkkkkk....
................................
................................
................................"""
rows=art.strip('\n').split('\n')
assert len(rows)==32 and all(len(r)==32 for r in rows),[len(r) for r in rows]
im=Image.new('RGBA',(32,32),(0,0,0,0))
for y,r in enumerate(rows):
  for x,ch in enumerate(r):
    if P[ch]: im.putpixel((x,y),P[ch])
im.save('icon32.png')
im.resize((256,256),Image.NEAREST).save('icon256.png')
im.resize((96,96),Image.NEAREST).resize((48,48),Image.BOX).save('icon48.png')
im.resize((16,16),Image.BOX).save('icon16.png')
big=im.resize((128,128),Image.NEAREST); big.save('icon128.png')
